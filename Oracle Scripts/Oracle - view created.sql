SELECT
    COUNT(*) AS ROW_COUNT,
    SUM(ORDER_AMOUNT) AS TOTAL_ORDER_AMOUNT,
    MIN(ORDER_AMOUNT) AS MIN_ORDER_AMOUNT,
    MAX(ORDER_AMOUNT) AS MAX_ORDER_AMOUNT
FROM ORACLE_SRC.ORDERS;

--create 6 views for CSV, JSON, PArquet data seperation

-- CSV group

-- CSV group
CREATE OR REPLACE VIEW ORACLE_SRC.CSV_CUSTOMERS AS
SELECT *
FROM ORACLE_SRC.CUSTOMERS
WHERE MOD(CUSTOMER_ID, 3) = 0;

CREATE OR REPLACE VIEW ORACLE_SRC.CSV_ORDERS AS
SELECT O.*
FROM ORACLE_SRC.ORDERS O
JOIN ORACLE_SRC.CUSTOMERS C
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE MOD(C.CUSTOMER_ID, 3) = 0;

-- JSON group
CREATE OR REPLACE VIEW ORACLE_SRC.JSON_CUSTOMERS AS
SELECT *
FROM ORACLE_SRC.CUSTOMERS
WHERE MOD(CUSTOMER_ID, 3) = 1;

CREATE OR REPLACE VIEW ORACLE_SRC.JSON_ORDERS AS
SELECT O.*
FROM ORACLE_SRC.ORDERS O
JOIN ORACLE_SRC.CUSTOMERS C
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE MOD(C.CUSTOMER_ID, 3) = 1;

-- PARQUET group
CREATE OR REPLACE VIEW ORACLE_SRC.PARQUET_CUSTOMERS AS
SELECT *
FROM ORACLE_SRC.CUSTOMERS
WHERE MOD(CUSTOMER_ID, 3) = 2;

CREATE OR REPLACE VIEW ORACLE_SRC.PARQUET_ORDERS AS
SELECT O.*
FROM ORACLE_SRC.ORDERS O
JOIN ORACLE_SRC.CUSTOMERS C
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE MOD(C.CUSTOMER_ID, 3) = 2;

-- Validate all six views
SELECT 'CSV_CUSTOMERS' AS VIEW_NAME, COUNT(*) AS ROW_COUNT FROM CSV_CUSTOMERS
UNION ALL
SELECT 'JSON_CUSTOMERS', COUNT(*) FROM JSON_CUSTOMERS
UNION ALL
SELECT 'PARQUET_CUSTOMERS', COUNT(*) FROM PARQUET_CUSTOMERS
UNION ALL
SELECT 'CSV_ORDERS', COUNT(*) FROM CSV_ORDERS
UNION ALL
SELECT 'JSON_ORDERS', COUNT(*) FROM JSON_ORDERS
UNION ALL
SELECT 'PARQUET_ORDERS', COUNT(*) FROM PARQUET_ORDERS;

