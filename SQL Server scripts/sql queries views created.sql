USE ENTERPRISE_SOURCE;
GO

-- CSV partition
CREATE OR ALTER VIEW SQLSERVER_SRC.CSV_PRODUCTS AS
SELECT *
FROM SQLSERVER_SRC.PRODUCTS
WHERE PRODUCT_ID % 3 = 0;
GO

CREATE OR ALTER VIEW SQLSERVER_SRC.CSV_INVENTORY AS
SELECT I.*
FROM SQLSERVER_SRC.INVENTORY I
JOIN SQLSERVER_SRC.PRODUCTS P
    ON P.PRODUCT_ID = I.PRODUCT_ID
WHERE P.PRODUCT_ID % 3 = 0;
GO

-- JSON partition
CREATE OR ALTER VIEW SQLSERVER_SRC.JSON_PRODUCTS AS
SELECT *
FROM SQLSERVER_SRC.PRODUCTS
WHERE PRODUCT_ID % 3 = 1;
GO

CREATE OR ALTER VIEW SQLSERVER_SRC.JSON_INVENTORY AS
SELECT I.*
FROM SQLSERVER_SRC.INVENTORY I
JOIN SQLSERVER_SRC.PRODUCTS P
    ON P.PRODUCT_ID = I.PRODUCT_ID
WHERE P.PRODUCT_ID % 3 = 1;
GO

-- PARQUET partition
CREATE OR ALTER VIEW SQLSERVER_SRC.PARQUET_PRODUCTS AS
SELECT *
FROM SQLSERVER_SRC.PRODUCTS
WHERE PRODUCT_ID % 3 = 2;
GO

CREATE OR ALTER VIEW SQLSERVER_SRC.PARQUET_INVENTORY AS
SELECT I.*
FROM SQLSERVER_SRC.INVENTORY I
JOIN SQLSERVER_SRC.PRODUCTS P
    ON P.PRODUCT_ID = I.PRODUCT_ID
WHERE P.PRODUCT_ID % 3 = 2;

GO

--VIEW PARTITION COUNTS

SELECT 'CSV_PRODUCTS' AS VIEW_NAME, COUNT(*) AS ROW_COUNT
FROM SQLSERVER_SRC.CSV_PRODUCTS
UNION ALL
SELECT 'JSON_PRODUCTS', COUNT(*)
FROM SQLSERVER_SRC.JSON_PRODUCTS
UNION ALL
SELECT 'PARQUET_PRODUCTS', COUNT(*)
FROM SQLSERVER_SRC.PARQUET_PRODUCTS
UNION ALL
SELECT 'CSV_INVENTORY', COUNT(*)
FROM SQLSERVER_SRC.CSV_INVENTORY
UNION ALL
SELECT 'JSON_INVENTORY', COUNT(*)
FROM SQLSERVER_SRC.JSON_INVENTORY
UNION ALL
SELECT 'PARQUET_INVENTORY', COUNT(*)
FROM SQLSERVER_SRC.PARQUET_INVENTORY;