
USE ENTERPRISE_SOURCE;
GO

-- PRODUCTS: add and backfill UPDATED_AT
ALTER TABLE SQLSERVER_SRC.PRODUCTS
ADD UPDATED_AT datetime2(7) NULL;
GO

UPDATE SQLSERVER_SRC.PRODUCTS
SET UPDATED_AT = CREATED_AT
WHERE UPDATED_AT IS NULL;
GO

ALTER TABLE SQLSERVER_SRC.PRODUCTS
ALTER COLUMN UPDATED_AT datetime2(7) NOT NULL;
GO

ALTER TABLE SQLSERVER_SRC.PRODUCTS
ADD IS_DELETED bit NOT NULL
    CONSTRAINT DF_PRODUCTS_IS_DELETED DEFAULT (0);
GO

ALTER TABLE SQLSERVER_SRC.PRODUCTS
ADD CONSTRAINT DF_PRODUCTS_UPDATED_AT
DEFAULT SYSUTCDATETIME() FOR UPDATED_AT;
GO

-- INVENTORY: preserve LAST_STOCK_UPDATE
ALTER TABLE SQLSERVER_SRC.INVENTORY
ADD UPDATED_AT datetime2(7) NULL;
GO

UPDATE SQLSERVER_SRC.INVENTORY
SET UPDATED_AT = LAST_STOCK_UPDATE
WHERE UPDATED_AT IS NULL;
GO

ALTER TABLE SQLSERVER_SRC.INVENTORY
ALTER COLUMN UPDATED_AT datetime2(7) NOT NULL;
GO

ALTER TABLE SQLSERVER_SRC.INVENTORY
ADD IS_DELETED bit NOT NULL
    CONSTRAINT DF_INVENTORY_IS_DELETED DEFAULT (0);
GO

ALTER TABLE SQLSERVER_SRC.INVENTORY
ADD CONSTRAINT DF_INVENTORY_UPDATED_AT
DEFAULT SYSUTCDATETIME() FOR UPDATED_AT;
GO

-- PRODUCTS automatic update timestamp
CREATE OR ALTER TRIGGER SQLSERVER_SRC.TRG_PRODUCTS_CDC
ON SQLSERVER_SRC.PRODUCTS
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF TRIGGER_NESTLEVEL() > 1 RETURN;

    UPDATE P
    SET UPDATED_AT = SYSUTCDATETIME()
    FROM SQLSERVER_SRC.PRODUCTS P
    INNER JOIN inserted I
        ON P.PRODUCT_ID = I.PRODUCT_ID;
END;
GO

-- INVENTORY automatic update timestamp
CREATE OR ALTER TRIGGER SQLSERVER_SRC.TRG_INVENTORY_CDC
ON SQLSERVER_SRC.INVENTORY
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF TRIGGER_NESTLEVEL() > 1 RETURN;

    UPDATE T
    SET UPDATED_AT = SYSUTCDATETIME()
    FROM SQLSERVER_SRC.INVENTORY T
    INNER JOIN inserted I
        ON T.INVENTORY_ID = I.INVENTORY_ID;
END;
GO
