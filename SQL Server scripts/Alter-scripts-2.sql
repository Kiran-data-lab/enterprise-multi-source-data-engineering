
USE ENTERPRISE_SOURCE;
GO

-- PRODUCTS
CREATE OR ALTER VIEW SQLSERVER_SRC.CSV_PRODUCTS AS
SELECT *
FROM SQLSERVER_SRC.PRODUCTS
WHERE PRODUCT_ID % 3 = 0;
GO

CREATE OR ALTER VIEW SQLSERVER_SRC.JSON_PRODUCTS AS
SELECT *
FROM SQLSERVER_SRC.PRODUCTS
WHERE PRODUCT_ID % 3 = 1;
GO

CREATE OR ALTER VIEW SQLSERVER_SRC.PARQUET_PRODUCTS AS
SELECT *
FROM SQLSERVER_SRC.PRODUCTS
WHERE PRODUCT_ID % 3 = 2;
GO

-- INVENTORY: partition by PRODUCT_ID
CREATE OR ALTER VIEW SQLSERVER_SRC.CSV_INVENTORY AS
SELECT *
FROM SQLSERVER_SRC.INVENTORY
WHERE PRODUCT_ID % 3 = 0;
GO

CREATE OR ALTER VIEW SQLSERVER_SRC.JSON_INVENTORY AS
SELECT *
FROM SQLSERVER_SRC.INVENTORY
WHERE PRODUCT_ID % 3 = 1;
GO

CREATE OR ALTER VIEW SQLSERVER_SRC.PARQUET_INVENTORY AS
SELECT *
FROM SQLSERVER_SRC.INVENTORY
WHERE PRODUCT_ID % 3 = 2;
GO
---------------------------
SELECT COUNT(*) TOTAL_ROWS,
       COUNT(IS_DELETED) DELETE_FLAGS,
       COUNT(UPDATED_AT) UPDATE_TIMESTAMPS
FROM SQLSERVER_SRC.PRODUCTS;

SELECT COUNT(*) TOTAL_ROWS,
       COUNT(IS_DELETED) DELETE_FLAGS,
       COUNT(UPDATED_AT) UPDATE_TIMESTAMPS
FROM SQLSERVER_SRC.INVENTORY;

SELECT TOP 2 * FROM SQLSERVER_SRC.CSV_PRODUCTS;
SELECT TOP 2 * FROM SQLSERVER_SRC.CSV_INVENTORY;
