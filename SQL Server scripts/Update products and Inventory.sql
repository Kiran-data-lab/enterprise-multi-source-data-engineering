-- Soft-delete one product (excluding test record PRODUCT_ID = 1)
UPDATE SQLSERVER_SRC.PRODUCTS
SET IS_DELETED = 1
WHERE PRODUCT_ID = (SELECT MIN(PRODUCT_ID) FROM SQLSERVER_SRC.PRODUCTS WHERE IS_DELETED = 0 AND PRODUCT_ID <> 1);

-- Soft-delete one inventory record (excluding test record INVENTORY_ID = 1)
UPDATE SQLSERVER_SRC.INVENTORY
SET IS_DELETED = 1
WHERE INVENTORY_ID = (SELECT MIN(INVENTORY_ID) FROM SQLSERVER_SRC.INVENTORY WHERE IS_DELETED = 0 AND INVENTORY_ID <> 1);

