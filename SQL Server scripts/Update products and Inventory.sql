-- Update one product without changing its business value
UPDATE SQLSERVER_SRC.PRODUCTS
SET PRODUCT_NAME = PRODUCT_NAME
WHERE PRODUCT_ID = (
    SELECT MIN(PRODUCT_ID)
    FROM SQLSERVER_SRC.PRODUCTS
    WHERE IS_DELETED = 0
);

-- Update one inventory record without changing its business value
UPDATE SQLSERVER_SRC.INVENTORY
SET QUANTITY_ON_HAND = QUANTITY_ON_HAND
WHERE INVENTORY_ID = (
    SELECT MIN(INVENTORY_ID)
    FROM SQLSERVER_SRC.INVENTORY
    WHERE IS_DELETED = 0
);

