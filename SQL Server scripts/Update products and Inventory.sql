SELECT
    'PRODUCTS' AS ENTITY,
    COUNT(*) AS TOTAL_ROWS,
    MIN(UPDATED_AT) AS MIN_UPDATED_AT,
    MAX(UPDATED_AT) AS MAX_UPDATED_AT,
    SUM(CASE WHEN UPDATED_AT >= '2026-11-07T00:10:14.937'
             THEN 1 ELSE 0 END) AS MATCHED_ROWS
FROM SQLSERVER_SRC.PRODUCTS

UNION ALL

SELECT
    'INVENTORY',
    COUNT(*),
    MIN(UPDATED_AT),
    MAX(UPDATED_AT),
    SUM(CASE WHEN UPDATED_AT >= '2026-11-07T00:11:17.455'
             THEN 1 ELSE 0 END)
FROM SQLSERVER_SRC.INVENTORY;



SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE
FROM ENTERPRISE_SOURCE.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'SQLSERVER_SRC'
  AND TABLE_NAME IN ('PRODUCTS', 'INVENTORY')
ORDER BY TABLE_NAME, ORDINAL_POSITION;


