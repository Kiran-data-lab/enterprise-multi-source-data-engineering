

USE master;
GO

IF NOT EXISTS (
    SELECT 1
    FROM sys.sql_logins
    WHERE name = 'ETL_READER'
)
BEGIN
    CREATE LOGIN ETL_READER
    WITH PASSWORD = '*****',
         CHECK_POLICY = ON;
END;
GO

USE ENTERPRISE_SOURCE;
GO

IF NOT EXISTS (
    SELECT 1
    FROM sys.database_principals
    WHERE name = 'ETL_READER'
)
BEGIN
    CREATE USER ETL_READER FOR LOGIN ETL_READER;
END;
GO

GRANT SELECT ON SCHEMA::SQLSERVER_SRC TO ETL_READER;
GO