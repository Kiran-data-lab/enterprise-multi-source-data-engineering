/*
In your results, Why Snowflake reports one JSON row
Your Python extraction uses Pandas with orient="records", which writes JSON as a single outer array containing many objects, conceptually:

Your current Snowflake JSON file format has: STRIP_OUTER_ARRAY = FALSE

So Snowflake reads that entire array as one VARIANT record. We need to tell Snowflake to strip the outer array and read each object as a separate row.

Create a JSON file format for array-based JSON
Run this in your Snowflake worksheet:
*/
CREATE OR REPLACE FILE FORMAT ENTERPRISE_DW.RAW.FF_ENTERPRISE_JSON_ARRAY
    TYPE = JSON
    STRIP_OUTER_ARRAY = TRUE;

