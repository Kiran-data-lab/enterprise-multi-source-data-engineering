CREATE OR REPLACE TEMP TABLE ENTERPRISE_DW.RAW.TMP_ORACLE_ORDERS
LIKE ENTERPRISE_DW.RAW.RAW_ORACLE_ORDERS;

COPY INTO ENTERPRISE_DW.RAW.TMP_ORACLE_ORDERS
FROM @ENTERPRISE_DW.RAW.STG_ENTERPRISE_LANDING/oracle/20261112T120435Z/orders_parquet.parquet
FILE_FORMAT = (
    FORMAT_NAME = 'ENTERPRISE_DW.RAW.FF_ENTERPRISE_PARQUET_INFER'
)
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

SELECT *
FROM ENTERPRISE_DW.RAW.TMP_ORACLE_ORDERS
WHERE ORDER_ID = 1;

----
MERGE INTO ENTERPRISE_DW.RAW.RAW_ORACLE_ORDERS T
USING ENTERPRISE_DW.RAW.TMP_ORACLE_ORDERS S
ON T.ORDER_ID = S.ORDER_ID

WHEN MATCHED AND S.UPDATED_AT >= T.UPDATED_AT THEN
    UPDATE SET
        T.CUSTOMER_ID = S.CUSTOMER_ID,
        T.ORDER_DATE = S.ORDER_DATE,
        T.ORDER_AMOUNT = S.ORDER_AMOUNT,
        T.ORDER_STATUS = S.ORDER_STATUS,
        T.PAYMENT_METHOD = S.PAYMENT_METHOD,
        T.CURRENCY_CODE = S.CURRENCY_CODE,
        T.UPDATED_AT = S.UPDATED_AT,
        T.IS_DELETED = S.IS_DELETED

WHEN NOT MATCHED THEN
    INSERT (
        ORDER_ID, CUSTOMER_ID, ORDER_DATE, ORDER_AMOUNT,
        ORDER_STATUS, PAYMENT_METHOD, CURRENCY_CODE,
        CREATED_AT, UPDATED_AT, IS_DELETED
    )
    VALUES (
        S.ORDER_ID, S.CUSTOMER_ID, S.ORDER_DATE, S.ORDER_AMOUNT,
        S.ORDER_STATUS, S.PAYMENT_METHOD, S.CURRENCY_CODE,
        S.CREATED_AT, S.UPDATED_AT, S.IS_DELETED
    );

SELECT ORDER_ID, ORDER_AMOUNT, ORDER_STATUS, UPDATED_AT, IS_DELETED
