CREATE TABLE IF NOT EXISTS ENTERPRISE_DW.AUDIT.ETL_WATERMARK (
    SOURCE_SYSTEM              VARCHAR(30),
    SOURCE_TABLE               VARCHAR(100),
    LAST_SUCCESSFUL_WATERMARK TIMESTAMP_NTZ,
    LAST_RUN_AT                TIMESTAMP_NTZ,
    LAST_RUN_STATUS            VARCHAR(20),
    ROWS_EXTRACTED             NUMBER,
    UPDATED_AT                 TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

MERGE INTO ENTERPRISE_DW.AUDIT.ETL_WATERMARK T
USING (
    SELECT 'ORACLE' AS SOURCE_SYSTEM,
           'CUSTOMERS' AS SOURCE_TABLE,
           MAX(UPDATED_AT)::TIMESTAMP_NTZ AS MAX_WATERMARK
    FROM ENTERPRISE_DW.RAW.RAW_ORACLE_CUSTOMERS

    UNION ALL

    SELECT 'ORACLE', 'ORDERS',
           MAX(UPDATED_AT)::TIMESTAMP_NTZ
    FROM ENTERPRISE_DW.RAW.RAW_ORACLE_ORDERS

    UNION ALL

    SELECT 'SQLSERVER', 'PRODUCTS',
           MAX(UPDATED_AT)::TIMESTAMP_NTZ
    FROM ENTERPRISE_DW.RAW.RAW_SQLSERVER_PRODUCTS

    UNION ALL

    SELECT 'SQLSERVER', 'INVENTORY',
           MAX(UPDATED_AT)::TIMESTAMP_NTZ
    FROM ENTERPRISE_DW.RAW.RAW_SQLSERVER_INVENTORY
) S
ON T.SOURCE_SYSTEM = S.SOURCE_SYSTEM
AND T.SOURCE_TABLE = S.SOURCE_TABLE
WHEN NOT MATCHED THEN
    INSERT (
        SOURCE_SYSTEM,
        SOURCE_TABLE,
        LAST_SUCCESSFUL_WATERMARK
    )
    VALUES (
        S.SOURCE_SYSTEM,
        S.SOURCE_TABLE,
        S.MAX_WATERMARK
    );

    --verify
    SELECT *
FROM ENTERPRISE_DW.AUDIT.ETL_WATERMARK
ORDER BY SOURCE_SYSTEM, SOURCE_TABLE;
