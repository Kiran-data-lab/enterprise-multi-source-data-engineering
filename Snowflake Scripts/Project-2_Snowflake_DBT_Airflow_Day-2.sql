    UNION ALL

    SELECT
        'SQLSERVER_INVENTORY_ORPHAN_PRODUCTS',
        COUNT(*)
    FROM ENTERPRISE_DW.RAW.RAW_SQLSERVER_INVENTORY I
    LEFT JOIN ENTERPRISE_DW.RAW.RAW_SQLSERVER_PRODUCTS P
        ON I.PRODUCT_ID = P.PRODUCT_ID
    WHERE P.PRODUCT_ID IS NULL

