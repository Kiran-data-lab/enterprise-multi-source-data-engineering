        'ORACLE_ORDERS_ORPHAN_CUSTOMERS',
        COUNT(*)
    FROM ENTERPRISE_DW.RAW.RAW_ORACLE_ORDERS O
    LEFT JOIN ENTERPRISE_DW.RAW.RAW_ORACLE_CUSTOMERS C
        ON O.CUSTOMER_ID = C.CUSTOMER_ID
