SELECT
    PRODUCT_ID,
    TRIM(PRODUCT_NAME) AS PRODUCT_NAME,
    UPPER(TRIM(CATEGORY)) AS CATEGORY,
    TRIM(BRAND) AS BRAND,
    UNIT_PRICE,
    UPPER(TRIM(PRODUCT_STATUS)) AS PRODUCT_STATUS,
    LAUNCH_DATE,
    CREATED_AT,
    UPDATED_AT,
    COALESCE(IS_DELETED, FALSE) AS IS_DELETED
FROM {{ source('sqlserver_raw', 'raw_sqlserver_products') }}
