WITH INVENTORY_METRICS AS
(
    SELECT
        PRODUCT_ID,
        COUNT(INVENTORY_ID) AS INVENTORY_RECORDS,
        COUNT(DISTINCT WAREHOUSE_ID) AS TOTAL_WAREHOUSES,
        SUM(QUANTITY_ON_HAND) AS TOTAL_STOCK,
        SUM(
            CASE
                WHEN QUANTITY_ON_HAND <= REORDER_LEVEL THEN 1
                ELSE 0
            END
        ) AS WAREHOUSES_REQUIRING_REORDER
    FROM {{ ref('stg_sqlserver_inventory') }}
    WHERE IS_DELETED = FALSE
    GROUP BY PRODUCT_ID
)

SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.CATEGORY,
    P.BRAND,
    P.UNIT_PRICE,
    P.PRODUCT_STATUS,
    P.LAUNCH_DATE,
    COALESCE(I.INVENTORY_RECORDS, 0) AS INVENTORY_RECORDS,
    COALESCE(I.TOTAL_WAREHOUSES, 0) AS TOTAL_WAREHOUSES,
    COALESCE(I.TOTAL_STOCK, 0) AS TOTAL_STOCK,
    COALESCE(I.WAREHOUSES_REQUIRING_REORDER, 0)
        AS WAREHOUSES_REQUIRING_REORDER,
    CASE
        WHEN I.PRODUCT_ID IS NULL THEN 'NO_INVENTORY'
        WHEN I.WAREHOUSES_REQUIRING_REORDER > 0 THEN 'REORDER_REQUIRED'
        ELSE 'STOCK_AVAILABLE'
    END AS INVENTORY_STATUS
FROM {{ ref('stg_sqlserver_products') }} P
LEFT JOIN INVENTORY_METRICS I
    ON P.PRODUCT_ID = I.PRODUCT_ID
WHERE P.IS_DELETED = FALSE
