
WITH ORDER_METRICS AS
(
    SELECT
        CUSTOMER_ID,
        COUNT(ORDER_ID) AS TOTAL_ORDERS,
        SUM(ORDER_AMOUNT) AS LIFETIME_SPEND,
        AVG(ORDER_AMOUNT) AS AVERAGE_ORDER_AMOUNT,
        MIN(ORDER_DATE) AS FIRST_ORDER_DATE,
        MAX(ORDER_DATE) AS LAST_ORDER_DATE
    FROM {{ ref('stg_oracle_orders') }}
    GROUP BY CUSTOMER_ID
)

SELECT
    C.CUSTOMER_ID,
    CONCAT_WS(' ', C.FIRST_NAME, C.LAST_NAME) AS CUSTOMER_NAME,
    C.EMAIL,
    C.PHONE,
    C.CITY,
    C.COUNTRY,
    C.CUSTOMER_TYPE,
    C.CUSTOMER_STATUS,
    C.REGISTRATION_DATE,
    C.IS_DELETED,
    COALESCE(O.TOTAL_ORDERS, 0) AS TOTAL_ORDERS,
    COALESCE(O.LIFETIME_SPEND, 0) AS LIFETIME_SPEND,
    O.AVERAGE_ORDER_AMOUNT,
    O.FIRST_ORDER_DATE,
    O.LAST_ORDER_DATE,
    CASE
        WHEN O.TOTAL_ORDERS IS NULL THEN 'NO_ORDERS'
        WHEN O.TOTAL_ORDERS = 1 THEN 'FIRST_TIME'
        ELSE 'REPEAT_CUSTOMER'
    END AS CUSTOMER_ORDER_CATEGORY
FROM {{ ref('stg_oracle_customers') }} C
LEFT JOIN ORDER_METRICS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
